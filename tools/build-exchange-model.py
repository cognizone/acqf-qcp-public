#!/usr/bin/env python3
"""Build a standalone SHACL graph from the common model and one product profile.

All inputs are reviewed local files. No owl:imports or remote URLs are followed.
Run with --check to verify a committed export instead of replacing it.
"""
import argparse
import json
from pathlib import Path

from rdflib import BNode, Graph, Namespace, RDF, URIRef
from rdflib.collection import Collection
from rdflib.compare import to_canonical_graph

QCP = Namespace('https://data.acqf-qcp.africa/model/internal/')
SKOS = Namespace('http://www.w3.org/2004/02/skos/core#')
DCT = Namespace('http://purl.org/dc/terms/')
SH = Namespace('http://www.w3.org/ns/shacl#')
ACQF = 'https://data.acqf-qcp.africa/model/'
ETF = 'https://data.etf-qd.cogni.zone/model/'


def local_file(root, relative):
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or not path.is_file():
        raise ValueError(f'Missing or invalid local input: {path}')
    return path


def load(path):
    return Graph().parse(path, format='json-ld' if path.suffix == '.jsonld' else 'turtle')


def build(product_root, common_root):
    config = json.loads(local_file(product_root, 'publication/validation.json').read_text())
    common = load(local_file(common_root, 'docs/model/common/exchange-model.ttl'))
    profile = load(local_file(product_root, config['profile']))
    # A profile only binds existing property shapes. Structural rules stay in the common source.
    for subject, predicate, value in profile:
        if (subject, RDF.type, SH.PropertyShape) not in common or predicate not in {
            QCP.controlledVocabulary, QCP.controlledVocabularyCatalogue, QCP.startsWith
        }:
            raise ValueError(f'Invalid product binding: {subject} {predicate} {value}')
    shapes = common + profile
    overrides = json.loads(local_file(common_root, 'publication/common-vocabularies.json').read_text())
    vocabularies = {}

    def vocabulary(iri):
        if not isinstance(iri, URIRef):
            raise ValueError(f'Expected a vocabulary IRI: {iri}')
        if iri not in vocabularies:
            key = str(iri)
            if key in config['vocabularies']:
                root, relative = product_root, config['vocabularies'][key]
            elif key in overrides:
                root, relative = common_root, overrides[key]
            elif key.startswith(ACQF):
                root, relative = common_root, 'docs/model/' + key[len(ACQF):]
            elif key.startswith(ETF):
                root, relative = product_root, 'docs/model/' + key[len(ETF):]
            else:
                raise ValueError(f'No reviewed local vocabulary for {iri}')
            graph = load(local_file(root, relative))
            if (iri, RDF.type, SKOS.ConceptScheme) not in graph:
                raise ValueError(f'Expected ConceptScheme {iri} in {relative}')
            vocabularies[iri] = graph
        return vocabularies[iri]

    for shape in set(shapes.subjects(QCP.controlledVocabularyCatalogue, None)):
        for catalogue in list(shapes.objects(shape, QCP.controlledVocabularyCatalogue)):
            graph = vocabulary(catalogue)
            members = set(graph.subjects(SKOS.inScheme, catalogue))
            if not members:
                raise ValueError(f'Empty framework catalogue: {catalogue}')
            for member in members:
                schemes = set(graph.objects(member, DCT.relation))
                if len(schemes) != 1:
                    raise ValueError(f'Expected one level scheme for framework {member}')
                shapes.add((shape, QCP.controlledVocabulary, schemes.pop()))
        shapes.remove((shape, QCP.controlledVocabularyCatalogue, None))

    for shape in set(shapes.subjects(QCP.controlledVocabulary, None)):
        if (shape, SH['in'], None) in shapes:
            raise ValueError(f'Already has sh:in: {shape}')
        allowed = set()
        for scheme in shapes.objects(shape, QCP.controlledVocabulary):
            members = set(vocabulary(scheme).subjects(SKOS.inScheme, scheme))
            if not members or any(not isinstance(member, URIRef) for member in members):
                raise ValueError(f'Empty or invalid membership in {scheme}')
            allowed.update(members)
        head = BNode()
        Collection(shapes, head, sorted(allowed, key=str))
        shapes.add((shape, SH['in'], head))
        # Runtime must not add a second constraint from an out-of-date lookup cache.
        shapes.remove((shape, QCP.controlledVocabulary, None))
    return shapes


def render(graph):
    # Canonical blank nodes and sorted N-Triples (a Turtle subset) give repeatable bytes.
    lines = sorted(f'{s.n3()} {p.n3()} {o.n3()} .\n' for s, p, o in to_canonical_graph(graph))
    return '# Generated by tools/build-exchange-model.py; edit common model, profile or CV sources.\n' + ''.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--product-root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--common-root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = args.product_root / 'docs/model/exchange-model.ttl'
    content = render(build(args.product_root, args.common_root))
    if args.check:
        if output.read_text() != content:
            raise SystemExit(f'Stale validation export: {output}')
        print(f'Checked {output}')
    else:
        temporary = output.with_suffix('.ttl.tmp')
        temporary.write_text(content)
        temporary.replace(output)
        print(f'Generated {output}')


if __name__ == '__main__':
    main()
