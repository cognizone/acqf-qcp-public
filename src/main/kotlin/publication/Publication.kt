package publication

import java.io.File
import java.nio.file.Files

class Publication(val rootDir: File, val tools: Tools) {
    val products = file("products").listFiles().orEmpty().sortedBy { it.name }
        .filter { it.resolve("publication.json").isFile }.map(::Product)
    val siteDirectory = file("build/site")

    fun file(path: String) = rootDir.resolve(path)
    fun selectedProducts(name: String) = products.filter { name == "all" || it.name == name }
        .also { require(it.isNotEmpty()) { "Unknown product: $name" } }
    fun workspace(action: (File) -> Unit) {
        val parent = file("build/publication").apply { mkdirs() }
        val work = Files.createTempDirectory(parent.toPath(), "run-").toFile()
        try { action(work) } finally { work.deleteRecursively() }
    }
    // Folder conventions define inputs; manifests specify public routes and exceptions.
    fun resources(): Map<String, File> {
        val result = linkedMapOf<String, File>()
        fun add(source: File, path: String) {
            inside(rootDir, source)
            require(source.exists()) { "Missing site source: $source" }
            for (input in source.walkTopDown().filter { it.isFile }) {
                val suffix = if (source.isDirectory) input.relativeTo(source).path else ""
                val target = inside(siteDirectory, siteDirectory.resolve(path).resolve(suffix))
                val relative = target.relativeTo(siteDirectory).path
                check(result.put(relative, input) == null) { "Duplicate site output: $relative" }
            }
        }
        val shared = json(file("common/publication.json")).getAsJsonObject("paths")
        shared.entrySet().forEach { (folder, path) -> add(file("common/$folder"), path.asString) }
        val folders = mapOf("vocabularies" to "model", "documentation" to "", "assets" to "",
            "examples" to "model/examples", "model" to "model")
        for (config in products) {
            folders.forEach { (folder, path) ->
                val source = config.directory.resolve(folder)
                if (source.exists()) add(source, config.path(path))
            }
        }
        return result
    }
    fun buildModels(configs: List<Product>, destination: File, work: File) {
        val generated = configs.associateWith { assembleModel(it, work.resolve(it.name)) }
        for ((config, model) in generated) {
            config.model(destination).apply {
                parentFile.mkdirs()
                writeText("# Generated by publication/publish.sh build; edit model, profile or vocabulary sources.\n" + model.readText())
            }
        }
    }
    fun checkModels(configs: List<Product>, work: File, site: File? = null) {
        for (config in configs) {
            val folder = work.resolve(config.name).apply { mkdirs() }
            if (site == null) assembleModel(config, folder)
            else config.model(site).copyTo(folder.resolve("generated.ttl"), overwrite = true)
            println(tools.command("bash", "publication/tests/check.sh", rootDir.path, config.manifest.path, folder.path).trim())
        }
    }

    fun buildSite() = workspace { work ->
        val stage = work.resolve("site").apply { mkdirs() }
        val resources = resources()
        val targets = resources.keys.toList() + products.flatMap {
            listOf(it.model(stage), it.reference(stage)).map { target -> target.relativeTo(stage).path }
        }
        check(targets.size == targets.toSet().size) { "Duplicate static/model/reference publication targets" }
        resources.forEach { (path, source) -> source.copyTo(stage.resolve(path).apply { parentFile.mkdirs() }) }
        buildModels(products, stage, work)
        products.forEach { generateReference(it, stage, work.resolve("reference-${it.name}")) }
        val actual = stage.walkTopDown().filter { it.isFile }.map { it.relativeTo(stage).path }.toSet()
        check(actual == targets.toSet()) { "Generated site differs from declared publication targets" }
        check(!siteDirectory.exists() || siteDirectory.deleteRecursively()) { "Cannot clean generated site: $siteDirectory" }
        stage.copyRecursively(siteDirectory)
    }
    fun checkValidation() {
        for (config in products) {
            val tests = config.directory.resolve("tests")
            val paths = tests.resolve("published-paths.txt")
            if (paths.isFile) paths.readLines().forEach {
                check(siteFile(it, siteDirectory).isFile) { "Missing established public path: $it" }
            }
            val anchors = tests.resolve("reference-anchors.txt")
            if (anchors.isFile) {
                val html = config.reference(siteDirectory).readText()
                anchors.readLines().forEach { check("id=\"$it\"" in html) { "Missing established reference anchor: $it" } }
            }
        }
        workspace { work ->
            println(tools.command("bash", "publication/tests/check-inputs.sh", rootDir.path, work.path).trim())
            checkModels(products, work, siteDirectory)
        }
        println("Checked clean site, documentation, public paths and both product contracts")
    }
}

fun main(args: Array<String>) {
    require(args.size in 3..4) { "Usage: publication <command> <repository> <jena-bin> [product|all]" }
    val root = File(args[1]).canonicalFile
    val publication = Publication(root, Tools(root, File(args[2])))
    with(publication) {
        when (args[0]) {
            "buildSite" -> buildSite()
            "buildModels" -> workspace { buildModels(selectedProducts(args.getOrElse(3) { "all" }), file("build/models"), it) }
            "checkModels" -> workspace { checkModels(selectedProducts(args.getOrElse(3) { "all" }), it) }
            "checkValidation" -> checkValidation()
            "checkDocumentation" -> workspace { work -> products.forEach { checkCatalogueLinks(it, work.resolve(it.name)) } }
            "generateNqfList" -> generateNqfList()
            else -> error("Unknown publication command: ${args[0]}")
        }
    }
}
